"""
Milestone 4, step 2: run every query in queries.sql and check the answers against pandas.

Run from the repo root (after build_db.py):
    python 04_sql/run_queries.py

Writes:
    04_sql/results/<query name>.csv      one file per query
    04_sql/results_summary.md            first rows of every result
    04_sql/results/reconciliation.csv    SQL answers compared with independent pandas answers
"""
import re
import sqlite3
from pathlib import Path

import pandas as pd

SQL_DIR = Path("04_sql")
DB = SQL_DIR / "kenya_retail.db"
RES = SQL_DIR / "results"
RES.mkdir(parents=True, exist_ok=True)

con = sqlite3.connect(DB)
text = (SQL_DIR / "queries.sql").read_text(encoding="utf-8")
parts = re.split(r"(?m)^-- name:\s*(\S+)\s*\n", text)
queries = list(zip(parts[1::2], parts[2::2]))

results, summary = {}, ["**MILESTONE 4: SQL RESULTS SUMMARY**",
                        "Generated by 04_sql/run_queries.py. Full results are in 04_sql/results/.\n"]
for name, body in queries:
    purpose = re.search(r"(?m)^-- purpose:\s*(.*)$", body)
    df = pd.read_sql_query(body, con)
    df.to_csv(RES / f"{name}.csv", index=False)
    results[name] = df
    print(f"{name:<34} {len(df):>4} rows")
    summary.append(f"**{name}**")
    summary.append(purpose.group(1) if purpose else "")
    summary.append(f"Rows returned: {len(df)}")
    summary.append("```\n" + df.head(15).to_string(index=False) + "\n```\n")
(SQL_DIR / "results_summary.md").write_text("\n".join(summary), encoding="utf-8")

# ------------------------------------------------ reconciliation with pandas
sales = pd.read_csv("data/clean/sales_clean.csv", parse_dates=["date"])
checks = []


def check(name, sql_val, pd_val, tol=0.01):
    ok = abs(float(sql_val) - float(pd_val)) <= tol
    checks.append({"check": name, "sql_value": sql_val, "pandas_value": pd_val, "tolerance": tol,
                   "status": "PASS" if ok else "FAIL"})


q1 = results["q01_reconciliation"].iloc[0]
check("sales lines", q1["sales_lines"], len(sales), 0)
check("distinct transactions", q1["distinct_transactions"], sales["transaction_id"].nunique(), 0)
check("total revenue KES", q1["revenue_kes"], round(sales["revenue_kes"].sum(), 2), 1)
if "real_revenue_kes" in sales.columns:
    check("total real revenue KES", q1["real_revenue_kes"], round(sales["real_revenue_kes"].sum(), 2), 1)
check("known customers", q1["known_customers"], sales["customer_id"].nunique(), 0)

cat_rev = sales.groupby("category")["revenue_kes"].sum().sort_values(ascending=False)  # category is already in sales_clean
q2 = results["q02_category_share"]
check("top category revenue", q2["revenue_kes"].iloc[0], round(cat_rev.iloc[0]), 1)
check("top category name matches", int(q2["category"].iloc[0] == cat_rev.index[0]), 1, 0)

y = sales.groupby("year")["revenue_kes"].sum()
q4 = results["q04_monthly_growth"]
check("Dec 2025 yoy nominal growth pct", q4["yoy_nominal_pct"].iloc[-1],
      round(100 * (sales[sales.year_month == "2025-12"].revenue_kes.sum() /
                   sales[sales.year_month == "2024-12"].revenue_kes.sum() - 1), 1), 0.1)
q5 = results["q05_category_yoy"]
grp = sales.groupby(["category", "year"])["revenue_kes"].sum().unstack()
top_cat = q5["category"].iloc[0]
check(f"{top_cat} nominal growth pct", q5["nominal_growth_pct"].iloc[0],
      round(100 * (grp.loc[top_cat, 2025] / grp.loc[top_cat, 2024] - 1), 1), 0.1)

hol_days = sales.loc[sales["is_public_holiday"].astype(str).str.lower() == "true", "date"].nunique()
check("holiday days observed", len(results["q06_holiday_days"]), hol_days, 0)

cust = sales[sales["customer_known"].astype(str).str.lower() == "true"].groupby("customer_id")["revenue_kes"].sum()
cust = cust.sort_values(ascending=False)
top10_py = round(100 * cust.iloc[:int(round(len(cust) * 0.1))].sum() / cust.sum(), 1)
check("top 10% customers revenue share pct", results["q09_customer_deciles"]["revenue_share_pct"].iloc[0], top10_py, 0.5)

rfm_py = pd.read_csv("data/clean/customer_rfm.csv")
check("customers scored in RFM", results["q10_rfm_segments"]["customers"].sum(), len(rfm_py), 0)

chk = pd.DataFrame(checks)
chk.to_csv(RES / "reconciliation.csv", index=False)
print("\n=== RECONCILIATION (SQL versus pandas) ===")
print(chk.to_string(index=False))
failed = (chk["status"] == "FAIL").sum()
print(f"\n{len(chk) - failed} of {len(chk)} checks passed.")
con.close()
